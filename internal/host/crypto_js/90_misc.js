function setEngine(id, flags) {
  validateString(id, "id");
  if (flags !== undefined) validateNumber(flags, "flags");
  throw makeError(Error, "ERR_CRYPTO_ENGINE_UNKNOWN", 'Engine "' + id + '" was not found');
}

